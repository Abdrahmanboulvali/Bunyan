-- 1. جدول المشاريع والمواقع
CREATE TABLE projects (
    project_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name VARCHAR2(150) NOT NULL,
    location VARCHAR2(255),
    budget NUMBER(12, 2),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. جدول المواد الأساسية (إسمنت، حديد، إلخ)
CREATE TABLE materials (
    material_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_name VARCHAR2(100) NOT NULL,
    unit VARCHAR2(50) NOT NULL,
    unit_price NUMBER(10, 2)
);

-- 3. جدول المستخدمين والمشرفين
CREATE TABLE app_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(100) NOT NULL,
    phone_number VARCHAR2(20),
    role VARCHAR2(50) NOT NULL
);

-- 4. جدول سجل الاستهلاك الميداني
CREATE TABLE consumption_logs (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id NUMBER NOT NULL,
    material_id NUMBER NOT NULL,
    user_id NUMBER NOT NULL,
    quantity_consumed NUMBER(10, 2) NOT NULL,
    consumption_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    image_url VARCHAR2(500),
    notes VARCHAR2(1000),
    CONSTRAINT fk_project FOREIGN KEY (project_id) REFERENCES projects(project_id),
    CONSTRAINT fk_material FOREIGN KEY (material_id) REFERENCES materials(material_id),
    CONSTRAINT fk_user FOREIGN KEY (user_id) REFERENCES app_users(user_id)
);